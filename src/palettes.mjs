export function resolveColor(palette, expression) {
  const [role, alpha, ...extra] = expression.split('/');
  const color = palette[role];
  if (!color || extra.length || (alpha !== undefined && !/^[0-9A-F]{2}$/.test(alpha))) {
    throw new Error(`Unknown color expression: ${expression}`);
  }
  return alpha === undefined ? color : color.slice(0, 7) + alpha;
}
